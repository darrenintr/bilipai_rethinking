// `/x/player/v2` returns a deeply-nested `data.subtitle.subtitles[]`
// envelope. We accept it via a hand-rolled `init(from:)` rather than
// a `Codable` struct because the upstream occasionally omits the
// `author` block (older video, no AI subtitle yet) and the Swift
// decoder will reject the whole payload if any nested key is
// missing. The shape of interest is just the per-track metadata
// (lan / lan_doc / subtitle_url / id) — we discard the rest.

private struct LyricInfoPayload: Decodable {
    let subtitle: LyricSubtitleEnvelope?

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: DynamicKey.self)
        subtitle = try? container.decode(LyricSubtitleEnvelope.self, forKey: DynamicKey("subtitle"))
    }
}

private struct LyricSubtitleEnvelope: Decodable {
    let subtitles: [LyricTrackDTO]
}

private struct LyricTrackDTO: Decodable {
    let id: Int64
    let lan: String
    let lanDoc: String
    let subtitleURL: String
    let author: LyricAuthorDTO?

    enum CodingKeys: String, CodingKey {
        case id
        case lan
        case lanDoc = "lan_doc"
        case subtitleURL = "subtitle_url"
        case author
    }

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: DynamicKey.self)
        id = container.decodeInt64(keys: ["id"]) ?? 0
        lan = container.decodeString(keys: ["lan"]) ?? ""
        lanDoc = container.decodeString(keys: ["lan_doc", "lanDoc"]) ?? ""
        subtitleURL = container.decodeString(keys: ["subtitle_url", "subtitleUrl"]) ?? ""
        author = try? container.decode(LyricAuthorDTO.self, forKey: DynamicKey("author"))
    }

    var model: BiliLyricInfo {
        BiliLyricInfo(
            id: id,
            lan: lan,
            lanDoc: lanDoc,
            subtitleURL: subtitleURL,
            author: author?.name
        )
    }
}

private struct LyricAuthorDTO: Decodable {
    let name: String?
}

// MARK: - Danmaku XML parser

private final class BiliDanmakuXMLParser: NSObject, XMLParserDelegate {
    private var items: [BiliDanmakuItem] = []
    private var currentAttributes: String?
    private var currentText = ""
    private var ordinal = 0

    static func parse(data: Data) -> [BiliDanmakuItem] {
        let delegate = BiliDanmakuXMLParser()
        let parser = XMLParser(data: data)
        parser.delegate = delegate
        guard parser.parse() else {
            bpLog("Danmaku XML parse failed: \(parser.parserError?.localizedDescription ?? "unknown error")")
            return []
        }
        return delegate.items.sorted { $0.time < $1.time }
    }

    func parser(
        _ parser: XMLParser,
        didStartElement elementName: String,
        namespaceURI: String?,
        qualifiedName qName: String?,
        attributes attributeDict: [String: String] = [:]
    ) {
        guard elementName == "d" else { return }
        currentAttributes = attributeDict["p"]
        currentText = ""
    }

    func parser(_ parser: XMLParser, foundCharacters string: String) {
        guard currentAttributes != nil else { return }
        currentText += string
    }

    func parser(
        _ parser: XMLParser,
        didEndElement elementName: String,
        namespaceURI: String?,
        qualifiedName qName: String?
    ) {
        guard elementName == "d", let attributes = currentAttributes else { return }
        defer {
            currentAttributes = nil
            currentText = ""
        }

        let fields = attributes.split(separator: ",", omittingEmptySubsequences: false)
        guard fields.count >= 4,
              let time = Double(fields[0]),
              let mode = Int(fields[1]),
              let fontSize = Int(fields[2]),
              let color = Int(fields[3]) else {
            return
        }
        let text = currentText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        items.append(BiliDanmakuItem(
            id: ordinal,
            time: time,
            mode: mode,
            fontSize: fontSize,
            color: color,
            text: text
        ))
        ordinal += 1
    }
}

private extension Data {
    func biliDanmakuInflatedIfNeeded() -> Data {
        if looksLikeXML { return self }

        var capacity = Swift.max(count * 8, 64 * 1024)
        for _ in 0..<4 {
            var output = Data(count: capacity)
            let decodedCount = output.withUnsafeMutableBytes { outputBuffer in
                withUnsafeBytes { inputBuffer in
                    guard let outputBase = outputBuffer.bindMemory(to: UInt8.self).baseAddress,
                          let inputBase = inputBuffer.bindMemory(to: UInt8.self).baseAddress else {
                        return 0
                    }
                    return compression_decode_buffer(
                        outputBase,
                        capacity,
                        inputBase,
                        count,
                        nil,
                        COMPRESSION_ZLIB
                    )
                }
            }
            if decodedCount > 0 {
                output.removeSubrange(decodedCount..<output.count)
                return output
            }
            capacity *= 2
        }

        return self
    }

    private var looksLikeXML: Bool {
        guard let first = firstNonWhitespaceByte else { return false }
        return first == 60
    }

    private var firstNonWhitespaceByte: UInt8? {
        first { byte in
            byte != 32 &&
            byte != 10 &&
            byte != 13 &&
            byte != 9
        }
    }
}
